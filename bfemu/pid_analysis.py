def _guidance(name: str, before: int, after: int, settings: dict) -> str:
    prefix = name.rsplit("_", 1)[0]
    increased = after > before
    if name in _SLIDER_GUIDANCE:
        return _SLIDER_GUIDANCE[name][0 if increased else 1]
    if name == "simplified_pids_mode":
        if after == 0:
            return "Выключение упрощённой настройки прекращает пересчёт коэффициентов ползунками. Ранее установленные коэффициенты остаются в профиле."
        if after == 1:
            return "В этом режиме пересчитываются коэффициенты крена и тангажа. Коэффициенты рыскания сохраняются без пересчёта."
        return "В этом режиме упрощённая настройка распространяется на крен, тангаж и рыскание. Проверьте полученные коэффициенты всех трёх осей."
    if prefix == "p":
        return ("Повышение P может ускорить коррекцию, но увеличить риск колебаний и нагрузку на моторы."
                if increased else "Снижение P может уменьшить колебания, но ухудшить следование заданию.")
    if prefix == "i":
        return _I_GUIDANCE[0 if increased else 1]
    if prefix in ("d", "d_min"):
        return ("Повышение D может улучшить демпфирование, но усилить шум и нагрев моторов; модель не оценивает нагрев."
                if increased else "Снижение D может уменьшить реакцию на шум, но ослабить демпфирование и усилить отскок.")
    if prefix == "f":
        return ("Повышение Feedforward может ускорить реакцию на стик, но сделать её резкой или с перерегулированием."
                if increased else "Снижение Feedforward может смягчить реакцию, но замедлить отклик на стик.")
    if name == "tpa_mode":
        return ("На высоком газе TPA ослабляет P и D: колебания могут уменьшиться, но реакция на ошибку тоже ослабнет."
                if after == 0 else "На высоком газе TPA ослабляет только D, сохраняя P. Реакция на ошибку может быть сильнее, но риск колебаний — выше, чем при ослаблении P и D.")
    if name == "tpa_rate":
        return ("Большее TPA сильнее ослабляет выбранные компоненты на высоком газе; это может уменьшить колебания, но ослабить управление."
                if increased else "Меньшее TPA сохраняет больше усиления на высоком газе, но может повысить склонность к колебаниям.")
    if name == "tpa_breakpoint":
        return ("Более высокий порог откладывает применение TPA до большего газа: усиление сохраняется дольше, но колебания могут появиться раньше ограничения."
                if increased else "Более низкий порог включает TPA раньше: колебания могут уменьшиться, но выбранные составляющие ослабнут уже при меньшем газе.")
    if name == "motor_output_limit":
        return ("Более высокий предел увеличивает доступный выход и запас управления, но повышает возможную нагрузку на силовую установку."
                if increased else "Более низкий предел уменьшает доступную тягу и может ограничить управляющий запас при манёврах.")
    if name == "feedforward_max_rate_limit":
        if after == 0:
            return "Ограничитель выключен: Feedforward больше не ограничивается этим механизмом у максимального рейта по крену и тангажу. Это может сделать отклик резче и увеличить перерегулирование."
        if before == 0:
            return "Ограничитель включён: у максимального рейта он сдерживает Feedforward по крену и тангажу, помогая уменьшить перерегулирование. На рыскание этот предел не действует."
        return (("Большее значение допускает более сильный Feedforward до ограничения возле максимального рейта, поэтому отклик может быть резче. "
                 if increased else "Меньшее ненулевое значение сильнее ограничивает Feedforward возле максимального рейта, что может уменьшить перерегулирование, но смягчить отклик. ")
                + "Ограничитель действует только по крену и тангажу; ноль отключает его.")
    if name == "iterm_relax":
        if after == 0:
            return "I-term Relax выключен: накопление I больше не ослабляется этим механизмом при манёврах. Удержание может усилиться, но отскок после манёвра — увеличиться."
        axes = "крена и тангажа" if after in (1, 3) else "крена, тангажа и рыскания"
        inc = (" В варианте INC ослабляется только увеличение величины I; уменьшение накопленного I остаётся возможным."
               if after in (3, 4) else " Ослабление применяется как при увеличении, так и при уменьшении величины I.")
        return (f"I-term Relax действует на оси {axes}, ослабляя накопление I при быстрых командах. Это может уменьшить отскок, но ослабить удержание во время манёвра." + inc)
    if name == "iterm_relax_type":
        guidance = ("Вариант SETPOINT ослабляет интегрируемую ошибку по изменению заданной скорости. Это может уменьшить отскок, но ослабить удержание во время манёвра."
                    if after == 1 else "Вариант GYRO использует гироскоп и отфильтрованное задание для расчёта интегрируемой ошибки. Отклик I во время манёвра может отличаться от варианта SETPOINT.")
        return guidance + (" При выключенном I-term Relax выбранный способ не действует." if settings["iterm_relax"] == 0 else "")
    if name == "iterm_rotation":
        return ("При вращении пересчитывается направление накопленной I-коррекции. Это помогает сохранять её согласованность с ориентацией аппарата во время быстрых вращений."
                if after else "Направление накопленной I-коррекции больше не пересчитывается при вращении. После быстрых переворотов её действие может хуже соответствовать изменившейся ориентации аппарата.")
    if name == "use_integrated_yaw":
        return ("Включён интегрированный выход регулятора рыскания: сумма PID накапливается с затуханием вместо обычного прямого выхода. Характер реакции на рыскание меняется, поэтому настройки yaw могут потребовать отдельного подбора."
                if after else "Восстановлен обычный прямой выход суммы PID по рысканию без интегрирования всей суммы. Характер реакции меняется, поэтому настройки yaw могут потребовать отдельного подбора.")
    if name == "auto_profile_cell_count":
        if after == 0:
            return "Этот профиль остаётся активным независимо от числа банок и может использоваться, когда совпадение не найдено. Автоматический выбор другого профиля из него отключён."
        if after == -1:
            return "При определении числа банок до армирования контроллер может выбрать подходящий профиль. Если совпадения нет, он может перейти на профиль со значением 0. Вместе с профилем изменятся используемые настройки PID."
        if not -1 <= after <= 8:
            return "Это значение вне диапазона Betaflight 4.5: используйте -1, 0 или число банок от 1 до 8. Корректный автоматический выбор профиля нельзя предположить."
        return f"Профиль привязывается к аккумулятору с {after} элементами и может автоматически выбираться при совпадении. Переключение профиля изменит применяемые настройки PID."
    if name in _DIRECTION_GUIDANCE:
        guidance = _DIRECTION_GUIDANCE[name][0 if increased else 1]
        if name == "iterm_relax_cutoff" and settings["iterm_relax"] == 0:
            guidance += " При выключенном I-term Relax изменение частоты не влияет на его работу."
        if name in ("d_max_gain", "d_max_advance"):
            guidance += " Динамическое повышение возможно при наличии диапазона между базовым D и D Max."
        if name == "horizon_limit_sticks":
            guidance += " Если в прошивке включён horizon_ignore_sticks, положение стика не ослабляет самовыравнивание."
        if name == "dyn_idle_min_rpm":
            guidance += " Динамическому холостому ходу нужны данные об оборотах моторов; ноль отключает этот механизм."
        if name == "acro_trainer_angle_limit":
            guidance += " Это не жёсткая гарантия, что аппарат физически не превысит заданный угол."
        if name == "angle_limit":
            guidance += " Это ограничение команды, а не гарантия фактического угла при возмущениях."
        if name == "abs_control_gain":
            guidance += " Absolute Control требует включённого I-term Relax; при выключенном I-term Relax он не действует."
        if name == "horizon_level_strength" and after >= 100:
            guidance += " В Betaflight усиление Horizon ограничено сверху значением 100 процентов."
        return guidance
    raise KeyError(f"Нет объяснения настройки PID: {name}")


